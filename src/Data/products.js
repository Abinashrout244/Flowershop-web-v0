export const searchProducts = (query) =>
  products.filter(p =>
    p.name.toLowerCase().includes(query.toLowerCase()) ||
    p.category.toLowerCase().includes(query.toLowerCase()) ||
    p.occasions.some(o => o.toLowerCase().includes(query.toLowerCase()))
  );
